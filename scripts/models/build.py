"""Builds src/data/models.ts from scripts/models/raw.jsonl (old-site model pages).
Run: python3 scripts/models/build.py"""
import json, re, pathlib
root = pathlib.Path(__file__).resolve().parents[2]
BRAND_NAMES = {'mcintosh':'McIntosh','marantz':'Marantz','luxman':'Luxman','mark-levinson':'Mark Levinson','studer':'Studer','revox':'Revox','akai':'Akai','teac':'TEAC','tascam':'TASCAM','pioneer':'Pioneer','nagra':'Nagra'}
DROP_SPEC = re.compile(r'warrant|location|hours|price|market|value|cost|manufacturer|shipping|turnaround', re.I)
GENERIC = ['Full diagnostic and evaluation','Capacitor replacement','Cleaning of controls, switches and relays','Bias and DC offset calibration','Full performance testing before return']
out, seen = [], set()
for line in (root/'scripts/models/raw.jsonl').read_text().splitlines():
    r = json.loads(line); d = r['d']; brand = r['brand']
    name = d['name'].strip()
    bn = BRAND_NAMES[brand]
    short = name[len(bn):].strip() if name.lower().startswith(bn.lower()) else name
    slug = re.sub(r'[^a-z0-9]+', '-', short.lower()).strip('-')
    base, n = slug, 2
    while (brand, slug) in seen: slug, n = f'{base}-{n}', n + 1
    seen.add((brand, slug))
    specs = [[k, v] for k, v in d.get('specs', []) if not DROP_SPEC.search(k) and str(v).strip()]
    problems = []
    for p in d.get('problems', []):
        if ': ' in p:
            a, b = p.split(': ', 1); problems.append([a[0].upper() + a[1:], b[0].upper() + b[1:]])
        else:
            problems.append([p, ''])
    services = [s for s in d.get('services', []) if s.lower() not in ('lens repair','camera repair','projector repair','monitor repair')] or GENERIC
    years = d.get('years') or ''
    if not re.search(r'\d', years) or '+' in years: years = ''
    out.append({'brand': brand, 'slug': slug, 'name': name, 'short': short, 'type': d.get('type',''), 'years': years,
                'summary': d.get('summary',''), 'intro': d.get('intro',''), 'specs': specs, 'problems': problems,
                'services': services, 'oldPaths': [r['old']] + r.get('alias', [])})
ts = ('// Generated by scripts/models/build.py from scripts/models/raw.jsonl. Edit the JSONL, then re-run.\n'
      'export interface ModelPage { brand: string; slug: string; name: string; short: string; type: string; years: string; summary: string; intro: string; specs: string[][]; problems: string[][]; services: string[]; oldPaths: string[] }\n'
      'export const models: ModelPage[] = ' + json.dumps(out, ensure_ascii=False, indent=1) + ';\n')
(root/'src/data/models.ts').write_text(ts)
print(len(out), 'models written')
