// Regenerates render.yaml (including redirects from old .aspx URLs) from the site data.
// Run: node scripts/gen-render-yaml.ts
import { writeFileSync } from 'node:fs';
import { services } from '../src/data/services.ts';
import { boPages } from '../src/data/bang-olufsen.ts';
import { brands } from '../src/data/brands.ts';

const routes: [string, string][] = [
  ['/default.aspx', '/'], ['/Default.aspx', '/'], ['/home', '/'],
  ['/aboutUs.aspx', '/about/'],
  ['/howTo.aspx', '/how-to-get-service/'],
  ['/contact.aspx', '/contact/'],
  ['/Privacy-Policy.aspx', '/privacy/'],
  ['/Terms.aspx', '/terms/'], ['/terms.aspx', '/terms/'], ['/Conditions.aspx', '/terms/'],
  ['/Capacitor-Replacement.aspx', '/capacitor-replacement/'],
  ['/Start-New-Ticket.aspx', 'https://techmediagroup.repairshopr.com/check_ins'],
  ['/Bang_and_Olufsen/Bang-Olufsen-Main.aspx', '/bang-olufsen/'],
  ['/Bang-Olufsen-Main.aspx', '/bang-olufsen/'],
  ['/Bang_and_Olufsen/Band_and_Olufsen_Service.aspx', '/bang-olufsen/'],
  ['/services/bang-olufsen-service/', '/bang-olufsen/'],
  ['/services/camcorder-camera-deck-repair/', '/services/camera-camcorder-repair/'],
  ['/services/audio-receiver-repair/', '/hifi-audio-repair/'],
  ['/services/reel-to-reel-repair/', '/reel-to-reel-repair/'],
  ['/Audio-Recievers/Hifi-Audio.aspx', '/hifi-audio-repair/'],
  ['/Reel-To-Reel/Reel-To-Reel.aspx', '/reel-to-reel-repair/'],
  ['/Reel-To-Reel-Models/Reel-To-Reel.aspx', '/reel-to-reel-repair/'],
];
for (const s of services) for (const o of s.oldPaths ?? []) routes.push([o, `/services/${s.slug}/`]);
for (const p of boPages) for (const o of p.oldPaths ?? []) routes.push([o, `/bang-olufsen/${p.slug}/`]);
for (const b of brands) for (const o of b.oldPaths ?? []) routes.push([o, `/brands/${b.slug}/`]);
// Old per-model pages (e.g. /Reel-To-Reel-Models/Revox/Revox-B77.aspx) go to the brand page.
for (const b of brands) for (const pre of b.oldPrefixes ?? []) routes.push([`${pre}*`, `/brands/${b.slug}/`]);
// Any other old B&O bulletin falls back to the B&O hub.
routes.push(['/Bang_and_Olufsen/*', '/bang-olufsen/']);
routes.push(['/Audio-Recievers/*', '/hifi-audio-repair/']);
routes.push(['/Reel-To-Reel-Models/*', '/reel-to-reel-repair/']);

const seen = new Set<string>();
const lines = routes
  .filter(([src]) => (seen.has(src) ? false : (seen.add(src), true)))
  .map(([src, dst]) => `      - type: redirect\n        source: ${JSON.stringify(src)}\n        destination: ${JSON.stringify(dst)}`);

const yaml = `# Render Blueprint: https://render.com/docs/blueprint-spec
# Generated by scripts/gen-render-yaml.ts. Edit that script, not this file.
services:
  - type: web
    name: TekMediaGroup-website
    runtime: static
    buildCommand: npm ci && npm run build
    staticPublishPath: ./dist
    pullRequestPreviewsEnabled: true
    headers:
      - path: /_astro/*
        name: Cache-Control
        value: public, max-age=31536000, immutable
      - path: /*
        name: X-Content-Type-Options
        value: nosniff
    routes:
      # Old ASP.NET URLs -> new pages (keeps Google rankings and old links working).
      # Rules are checked in order, so specific paths come before wildcards.
${lines.join('\n')}
`;
writeFileSync(new URL('../render.yaml', import.meta.url), yaml);
console.log(`render.yaml written with ${lines.length} redirects`);
